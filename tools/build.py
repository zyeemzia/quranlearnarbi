"""Build the site after editing content.

    python tools/build.py

1. Validates every file in data/ (stops on any problem).
2. Bundles all data files into one minified data.bundle.js (what the site and book load).
3. Stamps a content hash into index.html / book.html (?v=...) and into sw.js,
   so browsers and the offline cache pick up the new version.

Copyright © ZyeemZia
"""
import hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')
ORDER = ['reading', 'writing', 'tajweed', 'vocab', 'grammar', 'daily', 'quran']


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def write(p, s):
    with open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)


def extract(src, pattern):
    m = re.search(pattern, src)
    if not m:
        return None
    return json.JSONDecoder().raw_decode(src, m.end())[0]


def main():
    files = [os.path.join(DATA, n + '.js') for n in ORDER if os.path.exists(os.path.join(DATA, n + '.js'))]
    r = subprocess.run([sys.executable, os.path.join(DATA, 'validate.py')] + files, cwd=DATA)
    if r.returncode:
        sys.exit('Validation failed. Fix the problems above, then run the build again.')

    out = ['/* Generated by tools/build.py from data/*.js. Edit the files in data/, not this one. Copyright © ZyeemZia */',
           'window.AQ = window.AQ || { units: [], alphabet: [], vocab: [] };']
    for p in files:
        src = read(p)
        al = extract(src, r'AQ\.alphabet\s*=\s*')
        if al is not None:
            out.append('AQ.alphabet=' + json.dumps(al, ensure_ascii=False, separators=(',', ':')) + ';')
        unit = extract(src, r'AQ\.units\.push\(\s*')
        out.append('AQ.units.push(' + json.dumps(unit, ensure_ascii=False, separators=(',', ':')) + ');')
    write(os.path.join(ROOT, 'data.bundle.js'), '\n'.join(out) + '\n')

    assets = ['app.css', 'app.js', 'common.js', 'data.bundle.js', 'book.css', 'book.js', 'fonts.css']
    h = hashlib.sha1()
    for a in assets:
        with open(os.path.join(ROOT, a), 'rb') as f:
            h.update(f.read())
    ver = h.hexdigest()[:10]

    for page in ['index.html', 'book.html']:
        p = os.path.join(ROOT, page)
        s = re.sub(r'((?:app|book)\.(?:css|js)|common\.js|data\.bundle\.js)\?v=[\w.-]+', r'\1?v=' + ver, read(p))
        write(p, s)

    sw = os.path.join(ROOT, 'sw.js')
    write(sw, re.sub(r"const VERSION = '[^']*';", "const VERSION = '" + ver + "';", read(sw)))

    size = os.path.getsize(os.path.join(ROOT, 'data.bundle.js'))
    print(f'Built data.bundle.js ({size // 1024} KB), version {ver}.')


if __name__ == '__main__':
    main()
